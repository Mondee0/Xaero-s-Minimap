# Generates src/palette_rgb.rs from the palette PNGs (used to draw the PNG map).
param([string]$ModDir = (Split-Path $PSScriptRoot -Parent))
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$palDir = Join-Path $ModDir 'assets\textures\gui\minimap'
$o = New-Object System.Text.StringBuilder
[void]$o.AppendLine('//! Generated by tools/generate-palette-rgb.ps1. Do not edit by hand.')
[void]$o.AppendLine('pub static RGB: [[u8; 3]; 256] = [')
for ($i = 0; $i -lt 256; $i++) {
    $path = Join-Path $palDir ('p{0:D3}.png' -f $i)
    $bmp = New-Object System.Drawing.Bitmap($path)
    $c = $bmp.GetPixel(0, 0)
    $bmp.Dispose()
    [void]$o.AppendLine("    [$($c.R), $($c.G), $($c.B)], // $i")
}
[void]$o.AppendLine('];')
Set-Content -Path (Join-Path $ModDir 'src\palette_rgb.rs') -Value $o.ToString() -NoNewline
Write-Host 'Generated src/palette_rgb.rs'
