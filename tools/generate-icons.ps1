# Converts the reference mob pictures into palette-index arrays for the map.
# The pictures live in assets/icons; each is sampled down to ICON_SIZE x ICON_SIZE
# and every pixel is matched to the closest color in the map's palette.
# Output: src/icons.rs
param(
    [string]$ModDir = (Split-Path $PSScriptRoot -Parent)
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$size = 14
$palDir = Join-Path $ModDir 'assets\textures\gui\minimap'
$iconDir = Join-Path $ModDir 'assets\icons'

# Palette RGB values, read back from the generated 1x1 textures.
$palette = @()
for ($i = 0; $i -lt 256; $i++) {
    $path = Join-Path $palDir ('p{0:D3}.png' -f $i)
    if (-not (Test-Path $path)) { continue }
    $bmp = New-Object System.Drawing.Bitmap($path)
    $c = $bmp.GetPixel(0, 0)
    $palette += [pscustomobject]@{
        Idx = $i; A = [int]$c.A; R = [int]$c.R; G = [int]$c.G; B = [int]$c.B
    }
    $bmp.Dispose()
}

function Nearest-Palette([int]$r, [int]$g, [int]$b) {
    $best = 0; $bestD = 1e18
    foreach ($p in $palette) {
        if ($p.A -eq 0) { continue }              # transparent
        if ($p.Idx -ge 132 -and $p.Idx -le 135) { continue }  # frame colors
        if ($p.Idx -eq 129) { continue }          # undiscovered
        $dr = $r - $p.R; $dg = $g - $p.G; $db = $b - $p.B
        $d = $dr * $dr + $dg * $dg + $db * $db
        if ($d -lt $bestD) { $bestD = $d; $best = $p.Idx }
    }
    return $best
}

$names = @(
    @('zombie', 'Zombie.jfif'),
    @('skeleton', 'skeleton.jfif'),
    @('spider', 'spider.jfif'),
    @('sheep', 'sheep.jfif'),
    @('pig', 'Pig.jfif'),
    @('cow', 'Cow.jfif'),
    @('chicken', 'chicken.png')
)

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('//! Generated by tools/generate-icons.ps1 from assets/icons. Do not edit by hand.')
[void]$out.AppendLine("pub const ICON_SIZE: usize = $size;")
[void]$out.AppendLine('pub static ICONS: &[(&str, &[u8])] = &[')
foreach ($entry in $names) {
    $key = $entry[0]
    $path = Join-Path $iconDir $entry[1]
    $img = New-Object System.Drawing.Bitmap($path)
    [void]$out.AppendLine("    (`"$key`", &[")
    for ($y = 0; $y -lt $size; $y++) {
        $line = '        '
        for ($x = 0; $x -lt $size; $x++) {
            $sx = [int](($x + 0.5) * $img.Width / $size)
            $sy = [int](($y + 0.5) * $img.Height / $size)
            $c = $img.GetPixel($sx, $sy)
            $idx = Nearest-Palette ([int]$c.R) ([int]$c.G) ([int]$c.B)
            $line += ('{0:D3}, ' -f $idx)
        }
        [void]$out.AppendLine($line.TrimEnd())
    }
    [void]$out.AppendLine('    ]),')
    $img.Dispose()
}
[void]$out.AppendLine('];')
Set-Content -Path (Join-Path $ModDir 'src\icons.rs') -Value $out.ToString() -NoNewline
Write-Host "Generated src/icons.rs with $($names.Count) icons at ${size}x${size}"
